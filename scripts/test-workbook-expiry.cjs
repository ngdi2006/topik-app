const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript')
const model={}
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/textbooks/workbook-entitlement.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:model})
const now=Date.parse('2026-11-16T10:00:00Z'),day=86400000
const active={workbook_access:true,workbook_access_expires_at:new Date(now+10*day).toISOString()}
assert.equal(model.workbookEntitlement(active,now).active,true)
assert.equal(model.workbookEntitlement(active,now+10*day).active,false,'expiry boundary must deny access')
assert.equal(model.workbookEntitlement({workbook_access:true},now).active,false,'legacy unlimited grants must require an explicit expiry')
assert.equal(model.workbookEntitlement({workbook_access:true,workbook_access_expires_at:'invalid'},now).active,false)
assert.equal(Date.parse(model.nextWorkbookExpiry(active,{action:'extend',days:30},now).expiresAt),now+40*day)
assert.equal(Date.parse(model.nextWorkbookExpiry({...active,workbook_access_expires_at:new Date(now-day).toISOString()},{action:'extend',days:7},now).expiresAt),now+7*day)
assert.equal(Date.parse(model.nextWorkbookExpiry({...active,workbook_access:false},{action:'extend',days:7},now).expiresAt),now+7*day)
const custom=model.nextWorkbookExpiry(active,{action:'set_expiry',expires_at:'2026-11-20T23:59:59+07:00'},now)
assert.equal(custom.expiresAt,'2026-11-20T16:59:59.000Z')
assert.throws(()=>model.nextWorkbookExpiry(active,{action:'set_expiry',expires_at:'2026-11-01T00:00:00Z'},now))
assert.equal(model.nextWorkbookExpiry(active,{action:'revoke'},now).enabled,false)
const book1=model.updateWorkbookVolumes({keep:'yes'},[1],{action:'extend',days:7},now)
assert.equal(book1.keep,'yes')
assert.equal(model.workbookEntitlement(book1,now,1).active,true)
assert.equal(model.workbookEntitlement(book1,now,2).active,false)
const both=model.updateWorkbookVolumes(book1,[2],{action:'extend',days:30},now)
assert.equal(Date.parse(model.workbookEntitlement(both,now,1).expiresAt),now+7*day)
assert.equal(Date.parse(model.workbookEntitlement(both,now,2).expiresAt),now+30*day)
const extended=model.updateWorkbookVolumes(both,[1,2],{action:'extend',days:5},now)
assert.equal(Date.parse(model.workbookEntitlement(extended,now,1).expiresAt),now+12*day)
assert.equal(Date.parse(model.workbookEntitlement(extended,now,2).expiresAt),now+35*day)
const migrated=model.updateWorkbookVolumes(active,[1],{action:'revoke'},now)
assert.equal(model.workbookEntitlement(migrated,now,1).active,false)
assert.equal(model.workbookEntitlement(migrated,now,2).expiresAt,active.workbook_access_expires_at)
assert.equal(model.workbookEntitlement(migrated,now,2).active,true)
assert.equal(model.workbookEntitlement({...active,workbook_access_volumes:{}},now,1).active,false,'explicit map takes precedence over legacy grant')
for(const invalid of [null,[],true,'invalid'])assert.equal(model.workbookEntitlement({...active,workbook_access_volumes:invalid},now,1).active,false,'malformed explicit volume grant must not fall back to legacy access')
assert.equal(model.workbookVolumeFromCode('eps-topik-2025-workbook-1'),1)
assert.equal(model.workbookVolumeFromCode('eps-topik-2025-workbook-2'),2)
assert.equal(model.workbookVolumeFromCode('eps-topik-2025-workbook-3'),null)
console.log('PASS timed workbook access: active/expired/boundary, legacy grant, extension, reactivation, date/timezone and revoke')
